// ---------------- 应用逻辑 ----------------

function loadPoints() {
  const src = fs.readFileSync(SRC, "utf8");
  const markerIdx = src.indexOf("grammarPoints");
  const eqIdx = src.indexOf("=", markerIdx);
  const startIdx = src.indexOf("[", eqIdx);
  const endIdx = src.lastIndexOf("]");
  const literal = src.slice(startIdx, endIdx + 1);
  return new Function(`return (${literal});`)();
}

const FIELDS = {
  s: "setsuzoku", m: "meaning", n: "note", a: "analysis",
  e0: ["examples", 0, "jp"], e0z: ["examples", 0, "zh"],
  e1: ["examples", 1, "jp"], e1z: ["examples", 1, "zh"],
  e2: ["examples", 2, "jp"], e2z: ["examples", 2, "zh"],
};

function getField(p, f) {
  const spec = FIELDS[f];
  if (typeof spec === "string") return p[spec];
  const [arr, i, k] = spec;
  if (!p[arr] || !p[arr][i]) return undefined;
  return p[arr][i][k];
}
function setField(p, f, val) {
  const spec = FIELDS[f];
  if (typeof spec === "string") { p[spec] = val; return; }
  const [arr, i, k] = spec;
  if (!p[arr][i]) p[arr][i] = { jp: "", zh: "" };
  p[arr][i][k] = val;
}

function normalize(s) {
  return String(s ?? "").replace(/\s+/g, " ").trim();
}

// 按等级分组的顺序数组（与导出脚本编号一致）
const points = loadPoints();
const byLevel = {};
for (const p of points) (byLevel[p.level] ||= []).push(p);

const results = { ok: [], unmatched: [], dropped: [], cut: [] };

for (const c of C) {
  const list = byLevel[c.lv];
  const p = list && list[c.n - 1];
  if (!p) { results.unmatched.push({ ...c, reason: "entry not found" }); continue; }

  if (c.field === "DROP") {
    p.examples.splice(c.from, 1);
    results.dropped.push(`${c.lv}第${c.n}条 例句${c.from + 1}`);
    continue;
  }
  if (c.field === "CUT") {
    const val = getField(p, "n") ?? "";
    const idx = val.indexOf(c.from);
    if (idx === -1) { results.unmatched.push({ ...c, reason: "cut marker not found" }); continue; }
    setField(p, "n", val.slice(0, idx));
    results.cut.push(`${c.lv}第${c.n}条`);
    continue;
  }

  const cur = getField(p, c.field);
  if (cur === undefined) { results.unmatched.push({ ...c, reason: "field missing" }); continue; }

  if (c.from === null) {
    setField(p, c.field, c.to);
    results.ok.push(`${c.lv}第${c.n}条 ${c.field}（整字段）`);
    continue;
  }

  if (cur.includes(c.from)) {
    setField(p, c.field, cur.replace(c.from, c.to));
    results.ok.push(`${c.lv}第${c.n}条 ${c.field}`);
  } else if (normalize(cur).includes(normalize(c.from))) {
    setField(p, c.field, cur.replace(c.from, c.to));
    results.ok.push(`${c.lv}第${c.n}条 ${c.field}（空白归一后命中）`);
  } else {
    results.unmatched.push({ ...c, current: cur.slice(0, 80) });
  }
}

// ---------------- 全局清理：接续里的表格残留符 + 全文(续表) ----------------
let cleanedSetsuzoku = 0, cleanedXubiao = 0;
for (const p of points) {
  if (p.setsuzoku && /[|{}]/.test(p.setsuzoku)) {
    p.setsuzoku = p.setsuzoku.replace(/[|{}]/g, "").replace(/\s{2,}/g, " ");
    cleanedSetsuzoku++;
  }
  for (const k of ["meaning", "note", "analysis", "setsuzoku"]) {
    if (p[k] && p[k].includes("(续表)")) {
      p[k] = p[k].replace(/\(续表\)/g, "");
      cleanedXubiao++;
    }
  }
}

// ---------------- 序列化写回（保持原一行的紧凑格式） ----------------
function serializePoint(p) {
  const parts = [
    `{ id: ${JSON.stringify(p.id)}, pattern: ${JSON.stringify(p.pattern)}, setsuzoku: ${JSON.stringify(p.setsuzoku)}, meaning: ${JSON.stringify(p.meaning)}, examples: [${p.examples.map((e) => `{ jp: ${JSON.stringify(e.jp)}, zh: ${JSON.stringify(e.zh)} }`).join(", ")}]`,
  ];
  if (p.note !== undefined && p.note !== "") parts.push(`note: ${JSON.stringify(p.note)}`);
  if (p.analysis !== undefined && p.analysis !== "") parts.push(`analysis: ${JSON.stringify(p.analysis)}`);
  parts.push(`level: ${JSON.stringify(p.level)}`);
  return `  ${parts.join(", ")} }`;
}

