/* ==================== 2) 例句级修正 ==================== */
function fixEx(id, jpSub, zh) {
  const p = byId[id];
  if (!p) { log.push(`[缺失] ${id} 例句`); return; }
  const ex = (p.examples || []).find((e) => e.jp && e.jp.includes(jpSub));
  if (!ex) { log.push(`[未命中例句] ${id} 「${jpSub}」`); return; }
  const oldZh = ex.zh;
  ex.zh = zh;
  log.push(`[例句] ${id} 「${jpSub.slice(0, 16)}…」 zh ${JSON.stringify(oldZh).slice(0, 20)} → ${JSON.stringify(zh).slice(0, 20)}`);
}

