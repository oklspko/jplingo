const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "app", "data", "jp-grammar-points.ts");

/* ==================== 载入 ==================== */
function loadPoints() {
  const src = fs.readFileSync(SRC, "utf8");
  const markerIdx = src.indexOf("grammarPoints");
  const eqIdx = src.indexOf("=", markerIdx);
  const startIdx = src.indexOf("[", eqIdx);
  const endIdx = src.lastIndexOf("]");
  const literal = src.slice(startIdx, endIdx + 1);
  return new Function(`return (${literal});`)();
}

const points = loadPoints();
const byId = {};
for (const p of points) byId[p.id] = p;

const log = [];

/* ==================== 1) 字段级重写 ==================== */
function setField(id, field, to) {
  const p = byId[id];
  if (!p) { log.push(`[缺失] ${id} ${field}`); return; }
  const key = { p: "pattern", s: "setsuzoku", m: "meaning", n: "note", a: "analysis" }[field];
  const old = p[key];
  p[key] = to;
  log.push(`[字段] ${id}.${field}  ${JSON.stringify(old).slice(0, 24)} → ${JSON.stringify(to).slice(0, 24)}`);
}

